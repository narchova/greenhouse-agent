"""Image generation tools for greenhouse plants using gemini-3.1-flash-lite-image."""
import re
import uuid
from typing import Any, Dict
from google import genai
from google.genai import types
from google.genai.types import GenerateContentConfig, Modality
from google.cloud import storage
from google.adk.tools import ToolContext

PROJECT_ID = "qwiklabs-gcp-03-2deba0eddfc5"
BUCKET_NAME = "greenhouse-plants-qwiklabs-gcp-03-2deba0eddfc5"


async def generate_plant_image(
    prompt: str,
    tool_context: ToolContext,
    plant_name: str = "plant",
) -> Dict[str, Any]:
    """Generate an image for a plant or care condition, save as artifact, and upload to public Cloud Storage.

    Args:
        prompt: Description of the plant image to generate (e.g. 'A vibrant green Monstera Deliciosa plant in a terracotta pot in natural morning light').
        tool_context: The ADK tool context used to save the artifact in the Playground.
        plant_name: Name of the plant to use in the filename (e.g. 'Monstera Deliciosa').

    Returns:
        A dictionary with the public image URL, filename, and status.
    """
    # 1. Generate image using gemini-3.1-flash-lite-image in global region
    client = genai.Client(vertexai=True, project=PROJECT_ID, location="global")
    response = client.models.generate_content(
        model="gemini-3.1-flash-lite-image",
        contents=prompt,
        config=GenerateContentConfig(response_modalities=[Modality.IMAGE]),
    )

    image_bytes = None
    mime_type = "image/jpeg"

    if response.candidates and response.candidates[0].content:
        for part in response.candidates[0].content.parts:
            if part.inline_data:
                image_bytes = part.inline_data.data
                mime_type = part.inline_data.mime_type or "image/jpeg"
                break

    if not image_bytes:
        return {
            "status": "error",
            "message": "No image was generated by the model.",
        }

    # Clean plant name for filename
    clean_name = re.sub(r"[^a-zA-Z0-9_-]", "-", plant_name.strip().lower())
    clean_name = re.sub(r"-+", "-", clean_name).strip("-") or "plant"
    ext = "jpg" if "jpeg" in mime_type or "jpg" in mime_type else "png"
    filename = f"{clean_name}-{uuid.uuid4().hex[:6]}.{ext}"

    # 2. Save artifact using tool_context.save_artifact
    artifact_part = types.Part.from_bytes(data=image_bytes, mime_type=mime_type)
    version = await tool_context.save_artifact(filename=filename, artifact=artifact_part)

    # 3. Upload bytes to public Cloud Storage bucket
    storage_client = storage.Client(project=PROJECT_ID)
    bucket = storage_client.bucket(BUCKET_NAME)
    blob = bucket.blob(filename)
    blob.upload_from_string(image_bytes, content_type=mime_type)

    public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/{filename}"

    return {
        "status": "success",
        "plant_name": plant_name,
        "filename": filename,
        "artifact_version": version,
        "public_url": public_url,
        "message": f"Generated image for '{plant_name}' and saved to Cloud Storage: {public_url}",
    }
